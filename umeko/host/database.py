"""Connection and SQL differences shared by the two Store backends."""
from __future__ import annotations

import sqlite3
from contextlib import contextmanager
from pathlib import Path


class DatabaseIntegrityError(Exception):
    """A write violated a database constraint."""


class DatabaseUnavailable(RuntimeError):
    """The configured database connection could not be established."""


class _PostgresRow(tuple):
    """Support positional access, named access and dict(row), as sqlite3.Row does."""

    def __new__(cls, values, columns):
        row = super().__new__(cls, values)
        row.columns = columns
        return row

    def keys(self):
        return self.columns.keys()

    def __getitem__(self, key):
        return super().__getitem__(self.columns[key] if isinstance(key, str) else key)


def _postgres_row_factory(cursor):
    columns = {}
    for index, column in enumerate(cursor.description or ()):
        columns.setdefault(column.name, index)
    return lambda values: _PostgresRow(values, columns)


class DatabaseConnection:
    def __init__(self, connection, *, postgres: bool):
        self._connection = connection
        self.postgres = postgres
        self.primary_id = ("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if postgres
                           else "INTEGER PRIMARY KEY AUTOINCREMENT")
        self.binary_type = "BYTEA" if postgres else "BLOB"
        self.case_insensitive_unique = "" if postgres else "COLLATE NOCASE UNIQUE"

    @staticmethod
    def _postgres_sql(sql):
        # Application queries use '?' placeholders, with no literal '?' in bound SQL.
        return sql.replace("%", "%%").replace("?", "%s")

    def execute(self, sql, params=()):
        if self.postgres:
            if params:
                return self._connection.execute(self._postgres_sql(sql), params)
            return self._connection.execute(sql)
        return self._connection.execute(sql, params)

    def executemany(self, sql, params):
        if self.postgres:
            with self._connection.cursor() as cursor:
                cursor.executemany(self._postgres_sql(sql), params)
            return
        self._connection.executemany(sql, params)

    def executescript(self, sql):
        if self.postgres:
            self._connection.execute(sql, prepare=False)
        else:
            self._connection.executescript(sql)

    def begin_write(self):
        if self.postgres:
            # Serialize the same read-then-write sections as BEGIN IMMEDIATE.
            self.execute("SELECT pg_advisory_xact_lock(1431127371)")
        else:
            self.execute("BEGIN IMMEDIATE")

    def lock_schema(self):
        if self.postgres:
            self.begin_write()

    def columns(self, table):
        if self.postgres:
            return {row[0] for row in self.execute(
                "SELECT attname FROM pg_attribute WHERE attrelid=to_regclass(?) "
                "AND attnum>0 AND NOT attisdropped", (table,),
            )}
        return {row[0] for row in self.execute("SELECT name FROM pragma_table_info(?)", (table,))}

    def case_insensitive_eq(self, column):
        # column is an identifier fixed by the calling statement.
        return f"lower({column})=lower(?)" if self.postgres else f"{column}=?"

    def insert_id(self, sql, params):
        if self.postgres:
            return self.execute(sql + " RETURNING id", params).fetchone()[0]
        return self.execute(sql, params).lastrowid


@contextmanager
def connect_database(path: Path | None, database_url: str | None):
    if database_url:
        if not database_url.startswith(("postgresql://", "postgres://")):
            raise ValueError("UMEKO_DATABASE_URL 必须以 postgresql:// 或 postgres:// 开头")
        try:
            import psycopg
        except ImportError:
            raise RuntimeError("PostgreSQL 后端需要安装 umeko[postgres]") from None
        try:
            connection = psycopg.connect(database_url, row_factory=_postgres_row_factory, connect_timeout=10)
        except psycopg.Error:
            raise DatabaseUnavailable("无法连接 PostgreSQL，请检查 UMEKO_DATABASE_URL 和数据库状态") from None
        try:
            with connection:
                yield DatabaseConnection(connection, postgres=True)
        except psycopg.IntegrityError as exc:
            raise DatabaseIntegrityError() from exc
        return

    connection = sqlite3.connect(path, timeout=10)
    connection.row_factory = sqlite3.Row
    try:
        connection.execute("PRAGMA foreign_keys=ON")
        with connection:
            yield DatabaseConnection(connection, postgres=False)
    except sqlite3.IntegrityError as exc:
        raise DatabaseIntegrityError(str(exc)) from exc
    finally:
        connection.close()
