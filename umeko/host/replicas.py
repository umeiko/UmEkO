"""PostgreSQL coordination for replicas that mount the same data and skill volumes."""
from __future__ import annotations

from contextlib import contextmanager
from dataclasses import replace
import hashlib
import json
import logging
from pathlib import Path
import threading
import time
import uuid

from ..cancellation import raise_if_cancelled
from ..runner import Run, RunManager, TERMINAL_STATUSES, _now
from .database import DatabaseUnavailable

logger = logging.getLogger(__name__)
_LIVE = "expires_at > clock_timestamp()"
_ACTIVE = "'queued','running','cancelling'"


class ReplicaLeaseLost(RuntimeError):
    """A replica with an expired lease may no longer publish work."""


class ReplicaRuntime:
    lease_seconds = 30
    heartbeat_seconds = 3

    def __init__(self, store, data_root: Path, skill_root: Path):
        if store.backend != "postgresql":
            raise RuntimeError("UMEKO_REPLICA_MODE 需要 PostgreSQL")
        self.store = store
        self.id = uuid.uuid4().hex
        self._stop = threading.Event()
        self._lost = threading.Event()
        self._thread = None
        self._held = threading.local()
        with store.connect() as db:
            db.lock_schema()
            db.executescript("""
                CREATE TABLE IF NOT EXISTS replica_volumes (
                    name TEXT PRIMARY KEY, path TEXT NOT NULL, volume_id TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS replica_owners (
                    id TEXT PRIMARY KEY, expires_at TIMESTAMPTZ NOT NULL
                );
                CREATE TABLE IF NOT EXISTS replica_runs (
                    id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES agent_sessions(id) ON DELETE CASCADE,
                    owner_id TEXT NOT NULL, status TEXT NOT NULL, created_at TEXT NOT NULL,
                    completed_at TEXT, reply TEXT, error TEXT, cancel_requested INTEGER NOT NULL DEFAULT 0
                );
                CREATE UNIQUE INDEX IF NOT EXISTS idx_replica_run_active ON replica_runs(session_id)
                    WHERE status IN ('queued','running','cancelling');
                CREATE INDEX IF NOT EXISTS idx_replica_run_finished ON replica_runs(completed_at);
                CREATE TABLE IF NOT EXISTS replica_run_events (
                    run_id TEXT NOT NULL REFERENCES replica_runs(id) ON DELETE CASCADE,
                    seq BIGINT NOT NULL, event_json TEXT NOT NULL, PRIMARY KEY(run_id,seq)
                );
                CREATE TABLE IF NOT EXISTS replica_model_calls (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    owner_id TEXT NOT NULL REFERENCES replica_owners(id) ON DELETE CASCADE,
                    model_key TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 0
                );
                CREATE INDEX IF NOT EXISTS idx_replica_model_calls ON replica_model_calls(model_key,active,id);
            """)
            for name, root in (("data", data_root), ("skills", skill_root)):
                self._verify_volume(db, name, root.resolve())

    @staticmethod
    def _verify_volume(db, name: str, root: Path):
        marker = root / (".umeko-replica-volume-" + name)
        expected = db.execute("SELECT path,volume_id FROM replica_volumes WHERE name=?", (name,)).fetchone()
        if marker.is_symlink():
            raise RuntimeError(f"多副本的 {name} 卷标识必须是普通文件")
        if expected is not None:
            actual = marker.read_text(encoding="ascii").strip() if marker.is_file() else ""
            if expected["path"] != str(root) or expected["volume_id"] != actual:
                raise RuntimeError(f"多副本的 {name} 目录必须挂载同一持久化卷，且容器内路径一致")
            return
        root.mkdir(parents=True, exist_ok=True)
        if not marker.exists():
            with marker.open("x", encoding="ascii") as output:
                output.write(uuid.uuid4().hex)
        actual = marker.read_text(encoding="ascii").strip()
        if len(actual) != 32 or any(char not in "0123456789abcdef" for char in actual):
            raise RuntimeError(f"多副本的 {name} 卷标识无效")
        db.execute("INSERT INTO replica_volumes VALUES(?,?,?)", (name, str(root), actual))

    @contextmanager
    def lock(self, scope: str, key: str = ""):
        # A separate lock namespace keeps lifecycle locks independent of Store.begin_write().
        held = self._held.__dict__.setdefault("keys", set())
        identity = (scope, key)
        if identity in held:
            yield
            return
        with self.store.connect() as db:
            db.advisory_session_lock(scope, key)
            held.add(identity)
            try:
                yield
            finally:
                held.remove(identity)

    def start(self):
        if self._thread is not None:
            return
        with self.store.connect() as db:
            db.execute("INSERT INTO replica_owners VALUES (?,clock_timestamp()+?*interval '1 second')",
                       (self.id, self.lease_seconds))
        self._thread = threading.Thread(target=self._heartbeat, name="umeko-replica", daemon=True)
        self._thread.start()

    def _heartbeat(self):
        last_success = time.monotonic()
        while not self._stop.wait(self.heartbeat_seconds):
            try:
                with self.store.connect() as db:
                    renewed = db.execute("UPDATE replica_owners SET expires_at=clock_timestamp()+?*interval '1 second' "
                                         f"WHERE id=? AND {_LIVE}", (self.lease_seconds, self.id)).rowcount
                if not renewed:
                    self._lost.set()
                    return
                last_success = time.monotonic()
            except Exception:
                logger.exception("Could not renew replica lease")
                if time.monotonic() - last_success >= self.lease_seconds:
                    self._lost.set()
                    return

    def stop(self):
        self._stop.set()
        if self._thread is not None:
            self._thread.join(timeout=5)
            with self.store.connect() as db:
                db.execute("DELETE FROM replica_owners WHERE id=?", (self.id,))
        self._lost.set()

    def require_owner(self, db):
        if self._lost.is_set() or not db.execute(
            f"SELECT 1 FROM replica_owners WHERE id=? AND {_LIVE} FOR SHARE", (self.id,),
        ).fetchone():
            raise ReplicaLeaseLost("副本执行租约已失效")

    def ready(self):
        try:
            with self.store.connect() as db:
                self.require_owner(db)
            return True
        except (DatabaseUnavailable, ReplicaLeaseLost):
            return False

    def settings(self, settings):
        return replace(settings, **{
            slot: replace(model, queue_factory=self.model_queue)
            for slot in ("text_model", "sub_model", "vision_model") if (model := getattr(settings, slot)) is not None
        })

    def model_queue(self, model):
        key = model.model_id or hashlib.sha256((model.base_url + "\0" + model.name).encode()).hexdigest()
        return ReplicaModelQueue(self, key, model.max_concurrent_requests)

    def reap_runs(self, db, cutoff: str):
        dead = db.execute(f"SELECT id,session_id FROM replica_runs r WHERE status IN ({_ACTIVE}) "
                          f"AND NOT EXISTS (SELECT 1 FROM replica_owners o WHERE o.id=r.owner_id AND {_LIVE}) "
                          "FOR UPDATE").fetchall()
        for row in dead:
            stamp, error = _now(), "执行副本已离线，请重新提交"
            seq = db.execute("SELECT COALESCE(MAX(seq),0)+1 FROM replica_run_events WHERE run_id=?", (row["id"],)).fetchone()[0]
            event = {"id": seq, "run_id": row["id"], "session_id": row["session_id"], "type": "run.failed",
                     "timestamp": stamp, "data": {"error": error}}
            db.execute("INSERT INTO replica_run_events VALUES(?,?,?)", (row["id"], seq, json.dumps(event, ensure_ascii=False)))
            db.execute("UPDATE replica_runs SET status='failed',completed_at=?,error=? WHERE id=?", (stamp, error, row["id"]))
        db.execute("DELETE FROM replica_runs WHERE completed_at<?", (cutoff,))
        db.execute(f"DELETE FROM replica_owners WHERE NOT ({_LIVE})")


class ReplicaModelQueue:
    def __init__(self, runtime: ReplicaRuntime, key: str, default: int):
        self.runtime, self.key, self.default = runtime, key, default

    def _count(self, db):
        row = db.execute("SELECT max_concurrent_requests FROM provider_models WHERE id=?", (self.key,)).fetchone()
        limit = row[0] if row else self.default
        tickets = db.execute("SELECT c.id,c.active FROM replica_model_calls c JOIN replica_owners o ON o.id=c.owner_id "
                             f"WHERE c.model_key=? AND o.{_LIVE} ORDER BY c.id", (self.key,)).fetchall()
        return limit, sum(row["active"] for row in tickets), [row["id"] for row in tickets if not row["active"]]

    def snapshot(self):
        with self.runtime.store.connect() as db:
            limit, active, waiting = self._count(db)
        return {"limit": limit, "active": active, "waiting": len(waiting)}

    @contextmanager
    def slot(self, should_cancel=None, on_wait=None):
        raise_if_cancelled(should_cancel)
        store = self.runtime.store
        with self.runtime.lock("model", self.key), store.connect() as db:
            self.runtime.require_owner(db)
            ticket = db.insert_id("INSERT INTO replica_model_calls(owner_id,model_key) VALUES(?,?)", (self.runtime.id, self.key))
        try:
            notified = False
            while True:
                raise_if_cancelled(should_cancel)
                with self.runtime.lock("model", self.key), store.connect() as db:
                    self.runtime.require_owner(db)
                    limit, active, waiting = self._count(db)
                    if waiting and ticket == waiting[0] and (limit == 0 or active < limit):
                        db.execute("UPDATE replica_model_calls SET active=1 WHERE id=?", (ticket,))
                        break
                if not notified and on_wait is not None:
                    on_wait()
                notified = True
                time.sleep(0.2)
            raise_if_cancelled(should_cancel)
            yield
        finally:
            with store.connect() as db:
                db.execute("DELETE FROM replica_model_calls WHERE id=?", (ticket,))


class StoredRun(Run):
    def __init__(self, store, row):
        super().__init__(row["id"], row["session_id"])
        self.store = store
        self._refresh(row)

    def _refresh(self, row):
        if row is not None:
            for key in ("status", "created_at", "completed_at", "reply", "error"):
                setattr(self, key, row[key])
            if row["cancel_requested"] and self.status not in TERMINAL_STATUSES:
                self.status = "cancelling"

    def events_after(self, event_id: int):
        with self.store.connect() as db:
            row = db.execute("SELECT * FROM replica_runs WHERE id=?", (self.id,)).fetchone()
            if row is None:
                self.status = "failed"
                return []
            self._refresh(row)
            return [json.loads(r[0]) for r in db.execute(
                "SELECT event_json FROM replica_run_events WHERE run_id=? AND seq>? ORDER BY seq", (self.id, event_id),
            )]

    def request_cancel(self):
        with self.store.connect() as db:
            db.execute(f"UPDATE replica_runs SET cancel_requested=1 WHERE id=? AND status IN ({_ACTIVE})", (self.id,))
            self._refresh(db.execute("SELECT * FROM replica_runs WHERE id=?", (self.id,)).fetchone())


class ReplicaRunManager(RunManager):
    def __init__(self, runtime: ReplicaRuntime, max_workers: int = 4):
        super().__init__(max_workers=max_workers)
        self.runtime, self.store = runtime, runtime.store
        self.on_finish = None

    def shutdown(self):
        for run in list(self.runs.values()):
            try:
                run.request_cancel()
            except ReplicaLeaseLost:
                continue
        super().shutdown()

    def submit(self, run, fn):
        def execute():
            try:
                fn()
            except ReplicaLeaseLost:
                logger.info("Lost Run ownership: %s", run.id)
            finally:
                self.forget(run.id)
        super().submit(run, execute)

    def create(self, session_id: str, *, emit_queued: bool = True):
        run = Run(f"run_{uuid.uuid4().hex}", session_id, _publish=self._publish)
        with self.store.connect() as db:
            self.runtime.require_owner(db)
            inserted = db.execute("INSERT INTO replica_runs(id,session_id,owner_id,status,created_at) VALUES(?,?,?,?,?) "
                                  f"ON CONFLICT(session_id) WHERE status IN ({_ACTIVE}) DO NOTHING",
                                  (run.id, session_id, self.runtime.id, run.status, run.created_at)).rowcount
            if not inserted:
                raise ValueError("当前 Session 已有任务正在运行")
        next_check = 0.

        def cancellation():
            nonlocal next_check
            if self.runtime._lost.is_set():
                return True
            stamp = time.monotonic()
            if stamp < next_check:
                return False
            next_check = stamp + .2
            with self.store.connect() as db:
                row = db.execute("SELECT cancel_requested,status FROM replica_runs WHERE id=?", (run.id,)).fetchone()
            return row is None or bool(row["cancel_requested"]) or row["status"] in TERMINAL_STATUSES

        run._remote_cancel = cancellation
        if emit_queued:
            from ..events import RUN_QUEUED
            run.emit(RUN_QUEUED)
        with self._lock:
            self.runs[run.id] = run
        return run

    def _publish(self, run, event):
        with self.store.connect() as db:
            self.runtime.require_owner(db)
            updated = db.execute("UPDATE replica_runs SET status=?,completed_at=?,reply=?,error=? "
                                 f"WHERE id=? AND owner_id=? AND status IN ({_ACTIVE})",
                                 (run.status, run.completed_at, run.reply, run.error, run.id, self.runtime.id)).rowcount
            if not updated:
                raise ReplicaLeaseLost("运行已失去执行归属")
            if run.finished and self.on_finish is not None:
                self.on_finish(db, run)
            db.execute("INSERT INTO replica_run_events VALUES(?,?,?)", (run.id, event["id"], json.dumps(event, ensure_ascii=False)))

    def get(self, run_id: str):
        local = self.runs.get(run_id)
        if local is not None:
            return local
        with self.store.connect() as db:
            row = db.execute("SELECT * FROM replica_runs WHERE id=?", (run_id,)).fetchone()
        if row is None:
            raise KeyError(f"未知运行：{run_id}")
        return StoredRun(self.store, row)

    def active(self, session_id: str):
        with self.store.connect() as db:
            row = db.execute(f"SELECT * FROM replica_runs WHERE session_id=? AND status IN ({_ACTIVE})", (session_id,)).fetchone()
        return StoredRun(self.store, row) if row else None

    def latest(self, session_id: str):
        with self.store.connect() as db:
            row = db.execute("SELECT * FROM replica_runs WHERE session_id=? ORDER BY created_at DESC,id DESC LIMIT 1",
                             (session_id,)).fetchone()
        return StoredRun(self.store, row) if row else None
