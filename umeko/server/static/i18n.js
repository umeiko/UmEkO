const I18N_SUPPORTED = ["zh-CN", "zh-TW", "en", "ko", "fr", "de", "it"];
let i18nCurrent = "zh-CN";

function detectLocale() {
  try {
    const saved = localStorage.getItem("umeko:locale");
    if (I18N_SUPPORTED.includes(saved)) return saved;
  } catch (_) {}
  const nav = ((navigator.languages && navigator.languages[0]) || navigator.language || "").toLowerCase();
  if (nav.startsWith("zh")) return /tw|hk|mo|hant/.test(nav) ? "zh-TW" : "zh-CN";
  for (const code of ["en", "ko", "fr", "de", "it"]) if (nav.startsWith(code)) return code;
  return "zh-CN";
}

function currentLocale() {
  return i18nCurrent;
}

function t(key, vars) {
  let text = I18N_LOCALES[i18nCurrent]?.[key] ?? I18N_LOCALES["zh-CN"][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.documentElement.lang = i18nCurrent;
}

function setLocale(locale, {persist = true} = {}) {
  if (!I18N_SUPPORTED.includes(locale)) locale = "zh-CN";
  const changed = locale !== i18nCurrent;
  i18nCurrent = locale;
  if (persist) {
    try { localStorage.setItem("umeko:locale", locale); } catch (_) {}
  }
  applyI18n();
  if (changed) document.dispatchEvent(new CustomEvent("localechange", {detail: {locale}}));
}

// 初始化：先于 app.js 执行，确保首屏即为目标语言
setLocale(detectLocale(), {persist: false});
